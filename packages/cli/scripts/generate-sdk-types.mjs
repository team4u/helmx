/** Collects compiled `.d.ts` files from `packages/protocol/dist/`. */
function collectProtocolDeclarations(repoRoot) {
  const protocolDist = path.join(repoRoot, 'packages/protocol/dist');
  const required = ['index.d.ts', 'browser.d.ts'];
  const missing = required.filter((rel) => !isRegularFile(path.join(protocolDist, rel)));
  if (missing.length > 0) {
    throw new Error(
      `[cli] missing @helmx/protocol declaration artifacts (${missing.join(', ')}) in ${protocolDist}; build @helmx/protocol first`,
    );
  }
  const files = {};
  for (const rel of collectFilesSorted(protocolDist, ['.d.ts'])) {
    let content = normalizeLineEndings(readFileSync(path.join(protocolDist, rel), 'utf8'));
    if (rel === 'index.d.ts' || rel === 'browser.d.ts') {
      content = `${PEERS_REFERENCE}${content}`;
    }
    files[`protocol/${rel}`] = content;
  }
  return files;
}

/** Emits `.d.ts` files for `packages/ui` in memory without touching its package tree. */
function emitUiDeclarations(repoRoot) {
  const pkgDir = path.join(repoRoot, 'packages/ui');
  const tsconfigPath = path.join(pkgDir, 'tsconfig.json');
  if (!isRegularFile(tsconfigPath)) {
    throw new Error(`[cli] missing @helmx/ui tsconfig at ${tsconfigPath}`);
  }
  const configFile = ts.readConfigFile(tsconfigPath, ts.sys.readFile);
  if (configFile.error) {
    throw new Error(
      `[cli] failed to read ${tsconfigPath}: ${ts.flattenDiagnosticMessageText(configFile.error.messageText, '\n')}`,
    );
  }
  const virtualOutDir = path.join(pkgDir, '.virtual-dts-out');
  const parsed = ts.parseJsonConfigFileContent(configFile.config, ts.sys, pkgDir, {
    noEmit: false,
    emitDeclarationOnly: true,
    declaration: true,
    declarationMap: false,
    sourceMap: false,
    incremental: false,
    noEmitOnError: false,
    rootDir: path.join(pkgDir, 'src'),
    outDir: virtualOutDir,
  });
  const effectiveOutDir = parsed.options.outDir ?? virtualOutDir;
  const host = ts.createCompilerHost(parsed.options);
  const emitted = new Map();
  host.writeFile = (fileName, text) => {
    if (!fileName.endsWith('.d.ts')) return;
    const rawRel = path.relative(effectiveOutDir, fileName);
    const rel = rawRel.replace(/\\/g, '/');
    if (rel === '' || rel === '..' || rel.startsWith('../') || path.isAbsolute(rawRel)) return;
    emitted.set(rel, normalizeLineEndings(text));
  };
  const program = ts.createProgram(parsed.fileNames, parsed.options, host);
  program.emit();

  if (!emitted.has('index.d.ts')) {
    throw new Error('[cli] failed to emit @helmx/ui/index.d.ts');
  }
  const files = {};
  for (const rel of [...emitted.keys()].sort(compareAscii)) {
    let content = emitted.get(rel);
    if (rel === 'index.d.ts') {
      content = `${PEERS_REFERENCE}${content}`;
    }
    files[`ui/${rel}`] = content;
  }
  return { files, emitted };
}

/**
 * Emits `.d.ts` files for `packages/plugin-client` in memory without touching its package tree.
 * Resolves `@helmx/ui` against the in-memory `.d.ts` map emitted by `emitUiDeclarations` so
 * `plugin-client` keeps `rootDir = packages/plugin-client/src` and preserves clean `'@helmx/ui'`
 * import specifiers in its emitted declarations.
 */
function emitPluginClientDeclarations(repoRoot, uiEmitted) {
  const pkgDir = path.join(repoRoot, 'packages/plugin-client');
  const tsconfigPath = path.join(pkgDir, 'tsconfig.json');
  if (!isRegularFile(tsconfigPath)) {
    throw new Error(`[cli] missing @helmx/plugin-client tsconfig at ${tsconfigPath}`);
  }
  const configFile = ts.readConfigFile(tsconfigPath, ts.sys.readFile);
  if (configFile.error) {
    throw new Error(
      `[cli] failed to read ${tsconfigPath}: ${ts.flattenDiagnosticMessageText(configFile.error.messageText, '\n')}`,
    );
  }
  const virtualOutDir = path.join(pkgDir, '.virtual-dts-out');
  const virtualUiDir = path.join(pkgDir, '.virtual-ui-dts');
  const parsed = ts.parseJsonConfigFileContent(configFile.config, ts.sys, pkgDir, {
    noEmit: false,
    emitDeclarationOnly: true,
    declaration: true,
    declarationMap: false,
    sourceMap: false,
    incremental: false,
    noEmitOnError: false,
    rootDir: path.join(pkgDir, 'src'),
    baseUrl: pkgDir,
    paths: {
      '@helmx/ui': ['./.virtual-ui-dts/index.d.ts'],
    },
    outDir: virtualOutDir,
  });
  const effectiveOutDir = parsed.options.outDir ?? virtualOutDir;
  const host = ts.createCompilerHost(parsed.options);
  const virtualUiFiles = new Map();
  for (const [rel, content] of uiEmitted.entries()) {
    virtualUiFiles.set(path.resolve(virtualUiDir, rel), content);
  }
  const origFileExists = host.fileExists.bind(host);
  const origReadFile = host.readFile.bind(host);
  const origGetSourceFile = host.getSourceFile.bind(host);
  host.fileExists = (fileName) => virtualUiFiles.has(path.resolve(fileName)) || origFileExists(fileName);
  host.readFile = (fileName) => virtualUiFiles.get(path.resolve(fileName)) ?? origReadFile(fileName);
  host.getSourceFile = (fileName, languageVersionOrOptions, onError, shouldCreateNewSourceFile) => {
    const virtualText = virtualUiFiles.get(path.resolve(fileName));
    if (virtualText !== undefined) {
      return ts.createSourceFile(fileName, virtualText, languageVersionOrOptions);
    }
    return origGetSourceFile(fileName, languageVersionOrOptions, onError, shouldCreateNewSourceFile);
  };
  const emitted = new Map();
  host.writeFile = (fileName, text) => {
    if (!fileName.endsWith('.d.ts')) return;
    const rawRel = path.relative(effectiveOutDir, fileName);
    const rel = rawRel.replace(/\\/g, '/');
    if (rel === '' || rel === '..' || rel.startsWith('../') || path.isAbsolute(rawRel)) return;
    emitted.set(rel, normalizeLineEndings(text));
  };
  const program = ts.createProgram(parsed.fileNames, parsed.options, host);
  program.emit();

  if (!emitted.has('index.d.ts')) {
    throw new Error('[cli] failed to emit @helmx/plugin-client/index.d.ts');
  }
  const files = {};
  for (const rel of [...emitted.keys()].sort(compareAscii)) {
    let content = emitted.get(rel);
    if (rel === 'index.d.ts') {
      content = `${PEERS_REFERENCE}${content}`;
    }
    files[`plugin-client/${rel}`] = content;
  }
  return files;
}

/** Builds the complete deterministic SDK types bundle object. */
export function buildSdkTypesBundle(options = {}) {
  const repoRoot = path.resolve(options.repoRoot ?? defaultRepoRoot);
  const cliPkgPath = path.join(repoRoot, 'packages/cli/package.json');
  const cliPkg = JSON.parse(readFileSync(cliPkgPath, 'utf8'));
  const sdkVersion = typeof cliPkg.version === 'string' && cliPkg.version.length > 0 ? cliPkg.version : '0.0.0';

  const uiDeclarations = emitUiDeclarations(repoRoot);
  const rawFiles = {
    ...collectProtocolDeclarations(repoRoot),
    ...uiDeclarations.files,
    ...emitPluginClientDeclarations(repoRoot, uiDeclarations.emitted),
    'shims/peers.d.ts': normalizeLineEndings(SHIM_PEERS_DTS),
    'shims/react.d.ts': normalizeLineEndings(SHIM_REACT_DTS),
    'shims/react-jsx-runtime.d.ts': normalizeLineEndings(SHIM_REACT_JSX_RUNTIME_DTS),
  };

  const files = {};
  for (const key of Object.keys(rawFiles).sort(compareAscii)) {
    files[key] = rawFiles[key];
  }

  return {
    formatVersion: SCHEMA_VERSION,
    sdkVersion,
    files,
  };
}

function computeInputsFingerprint({ repoRoot, cliPkgRoot, scriptPath }) {
  const hash = createHash('sha256');
  hash.update(`cli-sdk-types-schema:${SCHEMA_VERSION}\0`);
  hashFileInto(hash, 'cli/package.json', path.join(cliPkgRoot, 'package.json'));
  hashFileInto(hash, 'cli/scripts/generate-sdk-types.mjs', scriptPath);
  hashFileInto(hash, 'ui/tsconfig.json', path.join(repoRoot, 'packages/ui/tsconfig.json'));
  hashFileInto(hash, 'ui/package.json', path.join(repoRoot, 'packages/ui/package.json'));
  hashFileInto(hash, 'plugin-client/tsconfig.json', path.join(repoRoot, 'packages/plugin-client/tsconfig.json'));
  hashFileInto(hash, 'plugin-client/package.json', path.join(repoRoot, 'packages/plugin-client/package.json'));
  hashDirectoryInto(hash, 'protocol/dist-dts', path.join(repoRoot, 'packages/protocol/dist'), ['.d.ts']);
  hashDirectoryInto(hash, 'ui/src', path.join(repoRoot, 'packages/ui/src'), ['.ts', '.tsx']);
  hashDirectoryInto(hash, 'plugin-client/src', path.join(repoRoot, 'packages/plugin-client/src'), ['.ts', '.tsx']);
  return hash.digest('hex');
}

function sha256File(filePath) {
  return createHash('sha256').update(readFileSync(filePath)).digest('hex');
}

function readCache(cacheFile) {
  if (!isRegularFile(cacheFile)) return null;
  try {
    const parsed = JSON.parse(readFileSync(cacheFile, 'utf8'));
    if (
      parsed &&
      typeof parsed === 'object' &&
      parsed.schemaVersion === SCHEMA_VERSION &&
      typeof parsed.fingerprint === 'string' &&
      typeof parsed.outputSha256 === 'string' &&
      typeof parsed.fileCount === 'number' &&
      typeof parsed.payloadBytes === 'number'
    ) {
      return parsed;
    }
  } catch {
    // Ignore corrupt cache and rebuild cleanly.
  }
  return null;
}

function writeCacheAtomic(cacheFile, data) {
  mkdirSync(path.dirname(cacheFile), { recursive: true });
  const tmpFile = `${cacheFile}.${process.pid}.${Date.now()}.tmp`;
  writeFileSync(tmpFile, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
  renameSync(tmpFile, cacheFile);
}

/**
 * Generates and writes `packages/cli/dist/sdk-types-snapshot.js` with an input fingerprint cache.
 * Always verifies the output file SHA-256 on disk so a fresh `tsc` emit of the `null` stub
 * never causes a false cache hit.
 */
export function writeEmbeddedSdkTypesSnapshot(options = {}) {
  const cliPkgRoot = path.resolve(options.cliPkgRoot ?? defaultCliPkgRoot);
  const repoRoot = path.resolve(options.repoRoot ?? path.resolve(cliPkgRoot, '../..'));
  const scriptPath = options.scriptPath ?? fileURLToPath(import.meta.url);
  const outFile = path.join(cliPkgRoot, 'dist/sdk-types-snapshot.js');
  const outMapFile = path.join(cliPkgRoot, 'dist/sdk-types-snapshot.js.map');
  const cacheFile = path.join(repoRoot, 'node_modules/.cache/helmx-build/cli-sdk-types-fingerprint.json');
  const force = options.force === true || process.env.HELMX_CLEAN_DIST === '1';

  if (!existsSync(path.dirname(outFile))) {
    throw new Error(`[cli] ${path.dirname(outFile)} is missing; run tsc build first`);
  }

  const fingerprint = computeInputsFingerprint({ repoRoot, cliPkgRoot, scriptPath });
  if (!force && isRegularFile(outFile)) {
    const cached = readCache(cacheFile);
    if (cached && cached.fingerprint === fingerprint && sha256File(outFile) === cached.outputSha256) {
      rmSync(outMapFile, { force: true });
      return {
        cached: true,
        outFile,
        fileCount: cached.fileCount,
        payloadBytes: cached.payloadBytes,
      };
    }
  }

  const bundle = buildSdkTypesBundle({ repoRoot });
  const json = JSON.stringify(bundle);
  const compressed = deflateRawSync(Buffer.from(json, 'utf8'), { level: 9 });
  const base64 = compressed.toString('base64');
  const moduleSource = `// Auto-generated at @helmx/cli build time by scripts/generate-sdk-types.mjs.\nexport const EMBEDDED_SDK_TYPES_PAYLOAD = ${JSON.stringify(base64)};\n`;

  writeFileSync(outFile, moduleSource, 'utf8');
  rmSync(outMapFile, { force: true });

  const fileCount = Object.keys(bundle.files).length;
  const payloadBytes = Buffer.byteLength(base64, 'utf8');
  const outputSha256 = sha256File(outFile);
  writeCacheAtomic(cacheFile, {
    schemaVersion: SCHEMA_VERSION,
    fingerprint,
    outputSha256,
    fileCount,
    payloadBytes,
  });

  return {
    cached: false,
    outFile,
    fileCount,
    payloadBytes,
  };
}

function canonicalizeForCompare(filePath) {
  const resolved = path.resolve(filePath);
  try {
    return realpathSync.native(resolved);
  } catch {
    return resolved;
  }
}

function isMainModule() {
  const entry = process.argv[1];
  if (!entry) return false;
  const actual = canonicalizeForCompare(entry);
  const self = canonicalizeForCompare(fileURLToPath(import.meta.url));
  return process.platform === 'win32'
    ? actual.toLowerCase() === self.toLowerCase()
    : actual === self;
}

if (isMainModule()) {
  try {
    const res = writeEmbeddedSdkTypesSnapshot({ force: process.argv.includes('--force') });
    console.log(
      `[cli] sdk types snapshot ${res.cached ? 'cached' : 'generated'}: ${res.fileCount} files (${(res.payloadBytes / 1024).toFixed(1)} KiB base64) -> ${res.outFile}`,
    );
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}
