/**
 * Backend for the app template: persistent public doc items + two dual-schema actions + main screen + sidebar shortcut.
 * Keeps parity with the app-builder skill fullstack-template.md:
 * flushes after write (honesty rule: never misreport persistence); zero Emoji; both input and output schemas declared
 * (single-source Schema contract; omissions fail at doctor register).
 */
export const SCAFFOLD_INDEX_TS_APP = (id: string, label: string) => `/**
 * Full-stack micro-app backend entrypoint (id: ${id}): export default PluginDefinition.
 * Re-check with \`helmx plugins doctor\` after edits, then hot-install/update with \`helmx plugins install <dir> --enable\`.
 */
import { randomUUID } from 'node:crypto'
import type { PluginDefinition } from '@helmx/protocol'

interface Item {
  id: string
  title: string
  done: boolean
  createdAt: number
}

export default {
  id: '${id}',
  name: '${label}',
  description: 'Minimal full-stack micro-app: persistent items + add/toggle actions + main screen.',
  version: '0.1.0',
  clientRoot: './client',
  definePlugin(ctx) {
    // Persistent business data: public doc subscribed in real time by frontend usePluginDoc
    const items = ctx.doc<{ list: Item[] }>('items', { list: [] }, { public: true })

    // Shared outputSchema: actions return { ok: true }
    const okSchema = {
      type: 'object',
      properties: { ok: { type: 'boolean' } },
      required: ['ok'],
      additionalProperties: false,
    } as const

    ctx.action<{ title: string }, { ok: boolean }>({
      id: 'add_item',
      description: 'Add a new item',
      inputSchema: {
        type: 'object',
        properties: { title: { type: 'string', minLength: 1 } },
        required: ['title'],
        additionalProperties: false,
      },
      outputSchema: okSchema,
      exposeAsTool: true,
      async handler(input) {
        items.update((current) => ({
          list: [
            { id: randomUUID(), title: input.title, done: false, createdAt: Date.now() },
            ...current.list,
          ],
        }))
        await items.flush()
        return { ok: true }
      },
    })

    ctx.action<{ id: string; done: boolean }, { ok: boolean }>({
      id: 'set_done',
      description: 'Check or uncheck an item',
      inputSchema: {
        type: 'object',
        properties: { id: { type: 'string' }, done: { type: 'boolean' } },
        required: ['id', 'done'],
        additionalProperties: false,
      },
      outputSchema: okSchema,
      exposeAsTool: true,
      async handler(input) {
        items.update((current) => ({
          list: current.list.map((it) => (it.id === input.id ? { ...it, done: input.done } : it)),
        }))
        await items.flush()
        return { ok: true }
      },
    })

    // Full-stack app requirement: at least one ctx.ui.screen (surfaced under Plugin Center -> With views)
    ctx.ui.screen({
      id: 'main',
      label: '${label}',
      client: { module: 'index.tsx', export: 'MainScreen' },
    })

    // Sidebar shortcut (protocol allows screen:<pluginId>/<screenId> targets; optional and removable,
    // app remains accessible from Plugin Center -> With views)
    ctx.ui.sidebarItem({
      id: 'open-main',
      label: '${label}',
      icon: 'layout-grid',
      target: 'screen:${id}/main',
    })
  },
} satisfies PluginDefinition
`

/**
 * Frontend for the app template: canonical HIG composition using `@helmx/ui` primitives
 * (`Screen` + `ScreenToolbar` + `SearchBox` + `Tabs`/`TabCount` + `List`/`ListRow` + `DetailDrawer`)
 * and `@helmx/plugin-client` hooks (`usePluginDoc` + `usePluginAction` + `usePluginContext` + `useScreenDrawer`);
 * zero private stylesheet by default, zero variant="default", zero Emoji.
 */
export const SCAFFOLD_CLIENT_APP_TSX = `import { useMemo, useState, type KeyboardEvent, type ReactNode } from 'react'
import type { ScreenProps } from '@helmx/protocol/browser'
import {
  Badge,
  Button,
  Callout,
  Checkbox,
  DetailDrawer,
  EmptyState,
  Field,
  Input,
  KvGrid,
  List,
  ListRow,
  LoadingState,
  Screen,
  ScreenToolbar,
  SearchBox,
  Stack,
  StatusLight,
  TabCount,
  Tabs,
  TabsList,
  TabsTrigger,
  formatTime,
} from '@helmx/ui'
import {
  usePluginAction,
  usePluginContext,
  usePluginDoc,
  useScreenDrawer,
} from '@helmx/plugin-client'

interface Item {
  id: string
  title: string
  done: boolean
  createdAt: number
}

export function MainScreen(props: Partial<ScreenProps>): ReactNode {
  const ctx = usePluginContext()
  const doc = usePluginDoc<{ list: Item[] }>('items')
  const actions = usePluginAction({ notifyError: true })

  const [statusFilter, setStatusFilter] = useState<'all' | 'open' | 'done'>('all')
  const [query, setQuery] = useState('')
  const [draft, setDraft] = useState('')

  const list = doc?.list ?? []
  const doneCount = list.filter((it) => it.done).length
  const openCount = list.length - doneCount

  const drawer = useScreenDrawer({
    param: 'item',
    createParam: 'create',
    hasItem: (id) => doc === undefined || list.some((it) => it.id === id),
    scope: props,
  })

  const filtered = useMemo(
    () =>
      list.filter((it) => {
        if (statusFilter === 'open' && it.done) return false
        if (statusFilter === 'done' && !it.done) return false
        const q = query.trim().toLowerCase()
        if (q === '') return true
        return it.title.toLowerCase().includes(q)
      }),
    [list, statusFilter, query],
  )

  const selectedItem =
    drawer.itemId !== undefined ? list.find((it) => it.id === drawer.itemId) : undefined

  const openCreateDrawer = (): void => {
    setDraft('')
    actions.clearError()
    drawer.openCreate()
  }

  const resetFilters = (): void => {
    setStatusFilter('all')
    setQuery('')
  }

  const handleCreate = async (): Promise<void> => {
    const title = draft.trim()
    if (title === '') return
    const result = await actions.run('add_item', { title }, { key: 'add_item' })
    if (result !== undefined) {
      setDraft('')
      ctx.notify('Added item')
      drawer.close()
    }
  }

  const handleCreateKeyDown = (event: KeyboardEvent<HTMLDivElement>): void => {
    if ((event.metaKey || event.ctrlKey) && event.key === 'Enter' && draft.trim() !== '' && !actions.pending) {
      event.preventDefault()
      void handleCreate()
    }
  }

  return (
    <Screen
      layout="contained"
      title="Items Workbench"
      subtitle={\`\${doneCount} / \${list.length} completed\`}
      actions={
        <Button
          variant="primary"
          size="sm"
          icon="plus"
          disabled={actions.pending}
          onClick={openCreateDrawer}
        >
          <span className="pane-action-label">New Item</span>
        </Button>
      }
      toolbar={
        <ScreenToolbar
          label="Item filters"
          actions={
            <SearchBox
              variant="toolbar"
              size="sm"
              value={query}
              onChange={setQuery}
              placeholder="Filter items..."
              ariaLabel="Filter items"
            />
          }
        >
          <Tabs
            value={statusFilter}
            onValueChange={(next: string) => setStatusFilter(next === 'open' || next === 'done' ? next : 'all')}
            variant="pills"
            size="sm"
          >
            <TabsList aria-label="Item status">
              <TabsTrigger value="all">
                <span>All</span>
                <TabCount>{list.length}</TabCount>
              </TabsTrigger>
              <TabsTrigger value="open">
                <span>Open</span>
                <TabCount>{openCount}</TabCount>
              </TabsTrigger>
              <TabsTrigger value="done">
                <span>Done</span>
                <TabCount>{doneCount}</TabCount>
              </TabsTrigger>
            </TabsList>
          </Tabs>
        </ScreenToolbar>
      }
    >
      {doc === undefined ? (
        <LoadingState label="Loading items..." />
      ) : filtered.length === 0 ? (
        <EmptyState
          icon={list.length === 0 ? 'inbox' : 'search'}
          title={list.length === 0 ? 'No items yet' : 'No matching items'}
          hint={list.length === 0 ? 'Create your first item to get started.' : undefined}
          hintSubtle
          action={
            list.length === 0 ? (
              <Button variant="primary" size="sm" icon="plus" onClick={openCreateDrawer}>
                New Item
              </Button>
            ) : (
              <Button variant="secondary" size="sm" icon="rotate-ccw" onClick={resetFilters}>
                Reset Filters
              </Button>
            )
          }
        />
      ) : (
        <List label="Item list">
          {filtered.map((item) => (
            <ListRow
              key={item.id}
              selected={drawer.itemId === item.id}
              leading={
                <StatusLight
                  tone={item.done ? 'done' : 'idle'}
                  label={item.done ? 'Completed' : 'Open'}
                />
              }
              title={item.title}
              meta={<span className="mono tabular-nums">{formatTime(item.createdAt)}</span>}
              trailing={
                <Checkbox
                  checked={item.done}
                  disabled={actions.pendingKey === \`toggle:\${item.id}\`}
                  aria-label={\`Mark \${item.title} as \${item.done ? 'open' : 'completed'}\`}
                  onChange={(checked) => {
                    void actions.run('set_done', { id: item.id, done: checked }, { key: \`toggle:\${item.id}\` })
                  }}
                />
              }
              onSelect={() => drawer.openItem(item.id)}
            />
          ))}
        </List>
      )}

      <DetailDrawer
        open={drawer.creating}
        onClose={() => drawer.close()}
        title="New Item"
        footer={
          <>
            <div className="flex-1" />
            <Button variant="ghost" size="sm" disabled={actions.pending} onClick={() => drawer.close()}>
              Cancel
            </Button>
            <Button
              variant="primary"
              size="sm"
              icon="check"
              pending={actions.pendingKey === 'add_item'}
              disabled={draft.trim() === ''}
              onClick={() => void handleCreate()}
            >
              Create
            </Button>
          </>
        }
      >
        <div onKeyDown={handleCreateKeyDown}>
          <Stack gap="md">
            {actions.error !== undefined && <Callout tone="err">{actions.error}</Callout>}
            <Field label="Item title" required>
              <Input
                value={draft}
                placeholder="Enter item title..."
                disabled={actions.pending}
                onChange={(e) => setDraft(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === 'Enter' && draft.trim() !== '' && !actions.pending) {
                    e.preventDefault()
                    void handleCreate()
                  }
                }}
              />
            </Field>
          </Stack>
        </div>
      </DetailDrawer>

      <DetailDrawer
        open={!drawer.creating && selectedItem !== undefined}
        onClose={() => drawer.close()}
        title={selectedItem?.title ?? ''}
        titleExtra={
          selectedItem !== undefined ? (
            <Badge tone={selectedItem.done ? 'ok' : 'neutral'}>
              {selectedItem.done ? 'Completed' : 'Open'}
            </Badge>
          ) : undefined
        }
        meta={selectedItem?.id}
        footer={
          selectedItem !== undefined ? (
            <>
              <div className="flex-1" />
              <Button
                variant="secondary"
                size="sm"
                pending={actions.pendingKey === \`toggle:\${selectedItem.id}\`}
                onClick={() => {
                  void actions.run(
                    'set_done',
                    { id: selectedItem.id, done: !selectedItem.done },
                    { key: \`toggle:\${selectedItem.id}\` },
                  )
                }}
              >
                {selectedItem.done ? 'Mark Open' : 'Mark Completed'}
              </Button>
              <Button variant="ghost" size="sm" onClick={() => drawer.close()}>
                Close
              </Button>
            </>
          ) : undefined
        }
      >
        {selectedItem !== undefined && (
          <KvGrid
            items={[
              {
                key: 'Status',
                value: (
                  <Badge tone={selectedItem.done ? 'ok' : 'neutral'}>
                    {selectedItem.done ? 'Completed' : 'Open'}
                  </Badge>
                ),
              },
              {
                key: 'Created',
                value: <span className="mono tabular-nums">{formatTime(selectedItem.createdAt)}</span>,
              },
              { key: 'Data source', value: "public doc 'items' (live usePluginDoc subscription)" },
            ]}
          />
        )}
      </DetailDrawer>
    </Screen>
  )
}
`

