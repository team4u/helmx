/**
 * AskDoc approval contract: structured human-in-the-loop prompts with optional expectedStateSeq guard.
 */
import type { LocalizedText } from './locale.js'

export type AskFieldType = 'text' | 'select' | 'confirm' | 'choice' | 'model'

/** A single candidate option of a select or choice field. */
export interface AskFieldOption {
  label: LocalizedText
  value: string
  /** Optional secondary description shown below or beside the option label. */
  description?: LocalizedText
}

/** Definition of a single question field. */
export interface AskFieldSpec {
  name: string
  label: LocalizedText
  type: AskFieldType
  /** Candidate list when type is select or choice. */
  options?: Array<AskFieldOption>
  required?: boolean
  /** Optional pre-selected initial value (must match an option value for select/choice, or 'true'|'false' for confirm when non-empty). */
  defaultValue?: string
}

export type AskStatus = 'pending' | 'answered' | 'cancelled' | 'superseded'

/** Ask document (`GET /api/asks` list item). */
export interface AskSpec {
  id: string
  conversationId: number
  ownerPluginId?: string
  title: LocalizedText
  description?: LocalizedText
  /** Optional subtle guidance text displayed below the form fields. */
  hint?: LocalizedText
  fields: AskFieldSpec[]
  /** Optional CAS watermark: if the caller submits a conflicting expectedStateSeq, the host rejects with 409. */
  expectedStateSeq?: number
  status: AskStatus
  createdAt: number
}

/** Input for creating an AskDoc (`ctx.host.createAsk`); the host assigns id when absent and manages status/createdAt. */
export interface AskCreateSpec extends Omit<AskSpec, 'id' | 'status' | 'createdAt'> {
  /** Optional predefined ID (caller idempotent retry / external reference); generated by the host when absent. */
  id?: string
}

/**
 * Terminal result of createAsk: the three normal outcomes
 * (answered/cancelled/superseded) all resolve; only validation/I/O/host failures
 * reject. superseded means the ask was superseded; the caller should treat it as
 * having received no answer.
 */
export interface AskResult {
  id: string
  status: 'answered' | 'cancelled' | 'superseded'
  /** fieldName -> answer value; an empty object in non-answered states. */
  answers: Record<string, string>
}

/** Human-submitted answers (`POST /api/asks/:id/answer`). */
export interface AskAnswer {
  askId: string
  /** fieldName -> answer value. */
  answers: Record<string, string>
  answeredAt: number
}
